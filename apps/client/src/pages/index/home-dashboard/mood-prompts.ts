export const MOOD_PROMPT_SLICE_MS = 12 * 60 * 60 * 1000
const DAY_MS = 24 * 60 * 60 * 1000

/** 文案按东八区本地 00:00 / 12:00 切换，而不是 UTC 的 8 点 / 20 点。 */
export function moodPromptIndexAt(now = Date.now()): number {
  const localMs = now + 8 * 60 * 60 * 1000
  const day = Math.floor(localMs / DAY_MS)
  const half = localMs - day * DAY_MS < MOOD_PROMPT_SLICE_MS ? 0 : 1
  const block = day * 2 + half
  return ((block % MOOD_PROMPTS.length) + MOOD_PROMPTS.length) % MOOD_PROMPTS.length
}

export function currentMoodPrompt(now = Date.now()): MoodPrompt {
  return MOOD_PROMPTS[moodPromptIndexAt(now)]!
}

/** 距离下一个 12h 边界还有多少毫秒。 */
export function msUntilNextMoodPrompt(now = Date.now()): number {
  const localMs = now + 8 * 60 * 60 * 1000
  return MOOD_PROMPT_SLICE_MS - (localMs % MOOD_PROMPT_SLICE_MS)
}
